import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { format, resolveConfig } from 'prettier';
import { createGenerator } from 'ts-json-schema-generator';
import ts from 'typescript';
import { build } from 'vite';
import {
  WIDGET_DEFAULT_ACCESS_LEVEL,
  WIDGET_DEFAULT_MIN_TIER,
} from '@/config/featureDefaults';
import { WIDGET_DEFAULTS } from '@/config/widgetDefaults';
import { WIDGET_TYPE_LIST } from '@/functions/src/mcp/widgetTypeList';

const ENTRY = resolve(
  process.cwd(),
  'tests/helpers/widgetConfigServerEntry.ts'
);
const SCHEMAS_FILE = resolve(
  process.cwd(),
  'functions/src/mcp/widgetConfigSchemas.gen.ts'
);
const RUNTIME_FILE = resolve(
  process.cwd(),
  'functions/src/mcp/widgetConfigRuntime.gen.ts'
);
const UPDATE = !!process.env.UPDATE_WIDGET_CONFIG_SCHEMAS;
const HEADER =
  'Generated by tests/mcpWidgetConfigSchemas.test.ts; rerun it with UPDATE_WIDGET_CONFIG_SCHEMAS=1.';

interface RootSchema {
  properties: Record<string, Record<string, unknown>>;
  definitions?: Record<string, unknown>;
}

function schemas() {
  const root = createGenerator({
    path: ENTRY,
    tsconfig: resolve(process.cwd(), 'tsconfig.json'),
    type: 'WidgetConfigSchemaRoot',
    skipTypeCheck: true,
    expose: 'none',
    jsDoc: 'basic',
    topRef: false,
    additionalProperties: false,
  }).createSchema('WidgetConfigSchemaRoot') as unknown as RootSchema;
  // Anonymous types are named by source offsets; rename them so unrelated types.ts edits leave no drift.
  let text = JSON.stringify({
    widgets: root.properties,
    definitions: root.definitions ?? {},
  });
  Object.keys(root.definitions ?? {}).forEach((name, i) => {
    if (/^[A-Za-z0-9_]+$/.test(name)) return;
    const ref = (n: string) => JSON.stringify(`#/definitions/${n}`);
    text = text
      .split(ref(encodeURIComponent(name)))
      .join(ref(`Anonymous${i + 1}`))
      .split(JSON.stringify(name) + ':')
      .join(JSON.stringify(`Anonymous${i + 1}`) + ':');
  });
  if (/types\.ts-\d/.test(text))
    throw new Error('a schema still names a source offset');
  return JSON.parse(text) as {
    widgets: RootSchema['properties'];
    definitions: Record<string, unknown>;
  };
}

async function runtimeCode() {
  const out = await build({
    configFile: false,
    logLevel: 'silent',
    resolve: { alias: { '@': process.cwd() } },
    build: {
      write: false,
      minify: false,
      target: 'es2022',
      lib: { entry: ENTRY, formats: ['es'], fileName: 'runtime' },
    },
  });
  const [first] = Array.isArray(out) ? out : [out];
  if (!('output' in first)) throw new Error('vite returned a watcher');
  const chunk = first.output[0];
  if (chunk.type !== 'chunk' || chunk.imports.length)
    throw new Error('runtime bundle must be one self-contained chunk');
  // Comments dropped so a comment-only edit in the app leaves no drift.
  const { outputText } = ts.transpileModule(chunk.code, {
    compilerOptions: {
      removeComments: true,
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
    },
  });
  return outputText.replace(/^export \{[^}]*\};\s*$/m, '');
}

async function formatted(file: string, text: string) {
  const config = await resolveConfig(file);
  return format(text, { ...config, filepath: file });
}

async function schemasText() {
  return formatted(
    SCHEMAS_FILE,
    `// ${HEADER}\nexport interface WidgetConfigSchemaFile {\n  widgets: Readonly<Record<string, Record<string, unknown>>>;\n  definitions: Readonly<Record<string, unknown>>;\n}\n\n// JSON schema per widget config, from \`ConfigForWidget\` in types.ts.\nexport const WIDGET_CONFIG_SCHEMAS = JSON.parse(\n  ${JSON.stringify(JSON.stringify(schemas()))}\n) as WidgetConfigSchemaFile;\n`
  );
}

async function runtimeText() {
  const tables = {
    accessLevels: WIDGET_DEFAULT_ACCESS_LEVEL,
    minTiers: WIDGET_DEFAULT_MIN_TIER,
  };
  return formatted(
    RUNTIME_FILE,
    `/* eslint-disable */\n// @ts-nocheck\n// ${HEADER}\n// Bundled from utils/adminBuildingConfig.ts, utils/widgetConfigPersistence.ts and config/widgetDefaults.ts.\n${await runtimeCode()}\n\nexport interface WidgetConfigRuntime {\n  getAdminBuildingConfig(\n    type: string,\n    featurePermissions: ReadonlyArray<Record<string, unknown>>,\n    selectedBuildings: readonly string[]\n  ): Record<string, unknown>;\n  mergeWidgetConfig(\n    defaults: Record<string, unknown> | undefined,\n    adminConfig: Record<string, unknown> | undefined,\n    saved: Record<string, unknown> | undefined,\n    overrides: Record<string, unknown> | undefined\n  ): Record<string, unknown>;\n  appearanceKeys: readonly string[];\n  defaults: Readonly<Record<string, { config?: Record<string, unknown> }>>;\n  accessLevels: Readonly<Record<string, string>>;\n  minTiers: Readonly<Record<string, string>>;\n}\n\nconst TABLES = ${JSON.stringify(tables)};\n\nexport const WIDGET_CONFIG_RUNTIME: WidgetConfigRuntime = {\n  getAdminBuildingConfig,\n  mergeWidgetConfig,\n  appearanceKeys: APPEARANCE_CONFIG_KEY_LIST,\n  defaults: WIDGET_DEFAULTS,\n  ...TABLES,\n};\n`
  );
}

describe('connector widget config schemas', () => {
  it('match types.ts (UPDATE_WIDGET_CONFIG_SCHEMAS=1 rewrites them)', async () => {
    const text = await schemasText();
    if (UPDATE) writeFileSync(SCHEMAS_FILE, text);
    else expect(readFileSync(SCHEMAS_FILE, 'utf8'), HEADER).toBe(text);
  }, 60_000);

  it('cover every widget type, including every one Claude can add', () => {
    const { widgets } = schemas();
    expect(Object.keys(widgets).sort()).toEqual(
      Object.keys(WIDGET_DEFAULTS).sort()
    );
    for (const type of WIDGET_TYPE_LIST)
      expect(widgets[type]?.type, type).toBe('object');
  }, 60_000);
});

describe('connector widget config runtime', () => {
  it('matches the app code it is bundled from (UPDATE_WIDGET_CONFIG_SCHEMAS=1 rewrites it)', async () => {
    const text = await runtimeText();
    if (UPDATE) writeFileSync(RUNTIME_FILE, text);
    else expect(readFileSync(RUNTIME_FILE, 'utf8'), HEADER).toBe(text);
  }, 60_000);
});
