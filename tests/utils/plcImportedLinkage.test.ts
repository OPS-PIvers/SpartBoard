import { describe, expect, it } from 'vitest';
import { importedPlcLinkage } from '@/utils/plc';

const live = {
  id: 'p',
  name: 'Live',
  memberEmails: ['me@x.edu'],
  sheetUrl: 'https://docs.google.com/spreadsheets/d/live',
};

describe('importedPlcLinkage (security #16)', () => {
  it('never keeps the share sheet, only the PLC sheet when the share used one', () => {
    const shared = {
      id: 'p',
      name: 'Old',
      memberEmails: ['sharer@x.edu'],
      sheetUrl: 'https://docs.google.com/spreadsheets/d/sharer',
    };
    expect(importedPlcLinkage(live, shared)).toEqual(live);
  });

  it("adds no sheet when the shared run exported to the teacher's own sheet", () => {
    const shared = { id: 'p', name: 'Old', memberEmails: [] };
    expect(importedPlcLinkage(live, shared)).not.toHaveProperty('sheetUrl');
  });

  it('keeps the auto-made flag only for the same sheet', () => {
    const shared = { ...live, autoGenerated: true };
    expect(importedPlcLinkage(live, shared).autoGenerated).toBe(true);
    expect(
      importedPlcLinkage(live, { ...shared, sheetUrl: 'https://x/other' })
    ).not.toHaveProperty('autoGenerated');
  });
});
