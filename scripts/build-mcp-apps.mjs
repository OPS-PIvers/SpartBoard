// Bundles mcpApps/preview into one HTML string for the connector (functions/src/mcp/apps/previewApp.gen.ts).
// Run: node scripts/build-mcp-apps.mjs        (writes the file)
//      node scripts/build-mcp-apps.mjs --check (fails if the committed file is stale)
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { build } from 'vite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(root, 'functions/src/mcp/apps/previewApp.gen.ts');

export async function buildPreviewHtml() {
  const result = await build({
    configFile: false,
    root,
    logLevel: 'silent',
    publicDir: false,
    build: {
      write: false,
      minify: true,
      target: 'es2022',
      lib: {
        entry: resolve(root, 'mcpApps/preview/main.ts'),
        formats: ['iife'],
        name: 'SpartBoardPreview',
        fileName: () => 'preview.js',
      },
    },
  });
  const outputs = Array.isArray(result) ? result : [result];
  const chunk = outputs
    .flatMap((o) => o.output)
    .find((o) => o.type === 'chunk');
  if (!chunk) throw new Error('No script chunk was built.');
  const css = await readFile(resolve(root, 'mcpApps/preview/styles.css'), 'utf8');
  // A literal "</script" inside the bundle would end the inline script early.
  const js = chunk.code.replace(/<\/script/gi, '<\\/script');
  return [
    '<!doctype html><html lang="en"><head><meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<meta name="color-scheme" content="light dark">',
    '<title>SpartBoard preview</title>',
    // Same fonts as index.html; the resource's CSP allows these two hosts.
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Lexend:wght@400;500;600;700&family=Roboto+Mono:wght@500;700&display=swap">',
    `<style>${css}</style></head>`,
    '<body><main id="root" aria-live="polite"></main>',
    `<script>${js}</script></body></html>`,
  ].join('');
}

/** The module as the pre-commit prettier pass would leave it, so the check matches what is committed. */
export async function genModule(html) {
  const source = `// Generated by scripts/build-mcp-apps.mjs from mcpApps/preview; do not edit.\nexport const PREVIEW_HTML = ${JSON.stringify(html)};\n`;
  const options = (await resolveConfig(OUT)) ?? {};
  return format(source, { ...options, filepath: OUT });
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const next = await genModule(await buildPreviewHtml());
  if (process.argv.includes('--check')) {
    const current = await readFile(OUT, 'utf8').catch(() => '');
    if (current !== next) {
      console.error(
        'functions/src/mcp/apps/previewApp.gen.ts is stale. Run: node scripts/build-mcp-apps.mjs'
      );
      process.exit(1);
    }
    console.log('Preview bundle is up to date.');
  } else {
    await mkdir(dirname(OUT), { recursive: true });
    await writeFile(OUT, next);
    console.log(`Wrote ${OUT} (${Math.round(next.length / 1024)} KiB).`);
  }
}
