# Rasterises Inter (SIL OFL) into functions/src/mcp/wireframeFont.ts; run: python3 functions/scripts/generate-wireframe-font.py [path/to/Inter-SemiBold.otf]
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/opentype/inter/Inter-SemiBold.otf'
SIZES = {'label': 14, 'title': 20}
CHARS = [chr(c) for c in range(32, 127)] + [chr(0xB7), chr(0x2026)]
OUT = 'functions/src/mcp/wireframeFont.ts'


def size_table(px):
    font = ImageFont.truetype(FONT, px)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in CHARS:
        advance = round(font.getlength(ch))
        bbox = font.getbbox(ch, anchor='ls')
        if bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
            glyphs.append((ch, advance, 0, 0, 0, 0, ''))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        img = Image.new('L', (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
        data = ''.join('%x' % (v >> 4) for v in img.tobytes())
        glyphs.append((ch, advance, x0, y0, w, h, data))
    return ascent, descent, glyphs


lines = [
    '// Generated by functions/scripts/generate-wireframe-font.py from Inter SemiBold (SIL Open Font License 1.1); do not edit.',
    '// Each font: ascent|descent|glyphs, glyphs joined by ";" as codepoint,advance,x,y,w,h,4-bit alpha hex.',
]
for name, px in SIZES.items():
    ascent, descent, glyphs = size_table(px)
    records = ';'.join(
        '%d,%d,%d,%d,%d,%d,%s' % (ord(ch), adv, x, y, w, h, data)
        for ch, adv, x, y, w, h, data in glyphs
    )
    lines.append("export const %s_FONT_DATA =" % name.upper())
    lines.append("  '%d|%d|%s';" % (ascent, descent, records))

with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', OUT)
